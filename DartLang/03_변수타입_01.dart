main(){
  // 변수 타입 선언자
  // 정수(integer)
  int intNum1 = 30;
  // print(intNum1);

  int intNum2 = 20;

  // 사칙연산
  print("** 정수 사칙연산 **");
  print(intNum1 + intNum2);
  print(intNum1 - intNum2);
  print(intNum1 * intNum2);
  print(intNum1 / intNum2);
  print(intNum1 % intNum2); // 나머지 연산
  print(intNum1 ~/ intNum2); // 몫 연산

  // 실수
  double doubleNum1 = 1.5;
  double doubleNum2 = 0.2;

  print(doubleNum1 + doubleNum2);
  print(doubleNum1 - doubleNum2);
  print(doubleNum1 * doubleNum2);
  print(doubleNum1 / doubleNum2);
}